package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

// slug turns "clask list" into "clask-list".
func slug(cmd *cobra.Command) string {
	return strings.ReplaceAll(cmd.CommandPath(), " ", "-")
}

// generate replaces dir with one page per available command and returns
// the page count.
func generate(root *cobra.Command, dir, base string) (int, error) {
	root.DisableAutoGenTag = true
	root.InitDefaultCompletionCmd()
	if err := os.RemoveAll(dir); err != nil {
		return 0, err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, err
	}
	// cobra links to "clask_list.md"; Starlight serves "<base>clask-list/".
	link := func(name string) string {
		return base + strings.ReplaceAll(strings.TrimSuffix(name, ".md"), "_", "-") + "/"
	}
	n := 0
	order := 0
	var walk func(*cobra.Command) error
	walk = func(cmd *cobra.Command) error {
		if !cmd.IsAvailableCommand() && cmd != root || cmd.IsAdditionalHelpTopicCommand() {
			return nil
		}
		var buf bytes.Buffer
		if err := doc.GenMarkdownCustom(cmd, &buf, link); err != nil {
			return err
		}
		page := frontmatter(cmd, order) + tidy(buf.String())
		order++
		if err := os.WriteFile(filepath.Join(dir, slug(cmd)+".md"), []byte(page), 0o644); err != nil {
			return err
		}
		n++
		for _, c := range cmd.Commands() {
			if err := walk(c); err != nil {
				return err
			}
		}
		return nil
	}
	return n, walk(root)
}

func frontmatter(cmd *cobra.Command, order int) string {
	label := cmd.Name()
	if !cmd.HasParent() {
		label = "clask (overview)"
	}
	return fmt.Sprintf("---\ntitle: %s\ndescription: %s\nsidebar:\n  label: %s\n  order: %d\n---\n\n<!-- Generated by cmd/gendocs from the command's help text. Do not edit. -->\n\n",
		strconv.Quote(cmd.CommandPath()), strconv.Quote(cmd.Short), strconv.Quote(label), order)
}

// tidy drops cobra's "## command" heading (Starlight renders the title)
// and promotes "###" sections to "##" so they appear in the page outline.
func tidy(md string) string {
	lines := strings.Split(md, "\n")
	if len(lines) > 0 && strings.HasPrefix(lines[0], "## ") {
		lines = lines[1:]
	}
	for i, l := range lines {
		if strings.HasPrefix(l, "### ") {
			lines[i] = "## " + strings.TrimPrefix(l, "### ")
		}
	}
	return strings.TrimLeft(strings.Join(lines, "\n"), "\n")
}
